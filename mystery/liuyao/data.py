LIUSHEN = ["青龙", "朱雀", "勾陈", "螣蛇", "白虎", "玄武"]
# 日干 → 初爻起哪个六神（青龙的偏移）
GAN_TO_LIUSHEN_START = {"甲": 0, "乙": 0, "丙": 1, "丁": 1, "戊": 2,
                        "己": 3, "庚": 4, "辛": 4, "壬": 5, "癸": 5}


def liushen_for_lines(day_gan):
    """按日干排六神，返回初爻→上爻 6 个六神"""
    start = GAN_TO_LIUSHEN_START.get(day_gan, 0)
    return [LIUSHEN[(start + i) % 6] for i in range(6)]


# ── 旬空（按日干支推算当旬的两个空亡地支）──
def xunkong(day_gan, day_zhi):
    """返回当日旬空的两个地支"""
    g = GAN.index(day_gan)
    z = ZHI.index(day_zhi)
    base = (z - g) % 12      # 旬首（甲）所在地支位
    return (ZHI[(base + 10) % 12], ZHI[(base + 11) % 12])


